WITH source_data AS
(
   SELECT
      LEAD_CO_MNE,
      BRANCH_CO_MNE,
      MIS_DATE,
      ID,
      DESCRIPTION,
      SHORT_NAME,
      LEAD_CO_MNE1,
      BRANCH_CO_MNE1,
      MIS_DATE1,
      DESCRIPTION1,
      SHORT_NAME1,
      New_Flag,
      Changed_Flag,
      o_CREATED_BY,
      o_CREATED_TIME,
      o_UPDATED_BY,
      o_UPDATED_TIME,
      Key
   FROM
      {{ ref('int_EXPTRANS') }}
)
SELECT
   LEAD_CO_MNE LEAD_CO_MNE3,
   BRANCH_CO_MNE BRANCH_CO_MNE3,
   MIS_DATE MIS_DATE3,
   ID ID2,
   DESCRIPTION DESCRIPTION3,
   SHORT_NAME SHORT_NAME3,
   LEAD_CO_MNE1 LEAD_CO_MNE12,
   BRANCH_CO_MNE1 BRANCH_CO_MNE12,
   MIS_DATE1 MIS_DATE12,
   DESCRIPTION1 DESCRIPTION12,
   SHORT_NAME1 SHORT_NAME12,
   New_Flag New_Flag2,
   Changed_Flag Changed_Flag2,
   o_CREATED_BY o_CREATED_BY2,
   o_CREATED_TIME o_CREATED_TIME2,
   o_UPDATED_BY o_UPDATED_BY2,
   o_UPDATED_TIME o_UPDATED_TIME2,
   Key Key2
FROM
   source_data
WHERE
   NOT COALESCE(New_Flag = 'Insert', FALSE)
   AND NOT COALESCE(Changed_Flag = 'Update', FALSE)