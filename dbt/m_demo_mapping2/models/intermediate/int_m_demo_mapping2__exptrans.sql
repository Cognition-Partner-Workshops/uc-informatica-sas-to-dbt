WITH source_data AS
(
   SELECT
      SQ_demo_source1__LEAD_CO_MNE AS LEAD_CO_MNE,
      SQ_demo_source1__BRANCH_CO_MNE AS BRANCH_CO_MNE,
      SQ_demo_source1__MIS_DATE AS MIS_DATE,
      SQ_demo_source1__ID AS ID,
      SQ_demo_source1__DESCRIPTION AS DESCRIPTION,
      SQ_demo_source1__SHORT_NAME AS SHORT_NAME,
      Key,
      LEAD_CO_MNE AS LEAD_CO_MNE1,
      BRANCH_CO_MNE AS BRANCH_CO_MNE1,
      MIS_DATE AS MIS_DATE1,
      DESCRIPTION AS DESCRIPTION1,
      SHORT_NAME AS SHORT_NAME1
   FROM
      {{ ref('int_m_demo_mapping2__lkptrans') }}
),
results_with_locals AS
(
   SELECT
      LEAD_CO_MNE AS LEAD_CO_MNE,
      BRANCH_CO_MNE AS BRANCH_CO_MNE,
      MIS_DATE AS MIS_DATE,
      ID AS ID,
      DESCRIPTION AS DESCRIPTION,
      SHORT_NAME AS SHORT_NAME,
      Key AS Key,
      LEAD_CO_MNE1 AS LEAD_CO_MNE1,
      BRANCH_CO_MNE1 AS BRANCH_CO_MNE1,
      MIS_DATE1 AS MIS_DATE1,
      DESCRIPTION1 AS DESCRIPTION1,
      SHORT_NAME1 AS SHORT_NAME1,
      IFF((Key IS NULL), 'Insert',
      --** SSC-FDM-INF0003 - IIF FUNCTION MISSING 'ONFALSEVALUE' PARAMETER DEFAULTED TO NULL. REPLACE WITH APPROPRIATE DEFAULT VALUE BASED ON 'ONTRUEVALUE' PARAMETER DATA TYPE. **
      NULL) AS New_Flag,
      -- AES_DECRYPT(LEAD_CO_MNE1, SUBSTR(SHORT_NAME, 1, 3), 256): TRY_DECRYPT is the Snowflake AES decrypt;
      -- a value that is not ciphertext comes back unchanged, as the legacy run does, so it never equals MD5_tgt.
      COALESCE(TO_VARCHAR(TRY_DECRYPT(TRY_TO_BINARY(LEAD_CO_MNE1, 'HEX'), SUBSTR(SHORT_NAME, 1, 3))), LEAD_CO_MNE1) AS MD5_src,
      --** SSC-FDM-INF0022 - INFORMATICA ALLOWS CONFIGURABLE CHARACTER ENCODING VIA THE DATAMOVEMENTMODE PROPERTY (ASCII OR UNICODE), WHILE SNOWFLAKE ALWAYS USES UTF-8. DIFFERENT ENCODINGS CAN PRODUCE DIFFERENT MD5 HASHES FOR THE SAME INPUT STRING. **
      UPPER(MD5(IFF(LEAD_CO_MNE IS NULL
      AND BRANCH_CO_MNE IS NULL
      AND MIS_DATE IS NULL
      AND DESCRIPTION IS NULL
      AND SHORT_NAME IS NULL, NULL, IFNULL(TO_VARCHAR(LEAD_CO_MNE), '') || IFNULL(TO_VARCHAR(BRANCH_CO_MNE), '') || IFNULL(TO_VARCHAR(MIS_DATE), '') || IFNULL(TO_VARCHAR(DESCRIPTION), '') || IFNULL(TO_VARCHAR(SHORT_NAME), '')))) AS MD5_tgt,
      IFF(NOT (Key IS NULL)
      AND (MD5_tgt <> MD5_src), 'Update',
      --** SSC-FDM-INF0003 - IIF FUNCTION MISSING 'ONFALSEVALUE' PARAMETER DEFAULTED TO NULL. REPLACE WITH APPROPRIATE DEFAULT VALUE BASED ON 'ONTRUEVALUE' PARAMETER DATA TYPE. **
      NULL) AS Changed_Flag,
      'IDWUSER' AS o_CREATED_BY,
      TO_TIMESTAMP_NTZ('{{ var("business_date") }}') AS o_CREATED_TIME,
      'IDWUSER' AS o_UPDATED_BY,
      TO_TIMESTAMP_NTZ('{{ var("business_date") }}') AS o_UPDATED_TIME
   FROM
      source_data
)
SELECT
   LEAD_CO_MNE,
   BRANCH_CO_MNE,
   MIS_DATE,
   ID,
   DESCRIPTION,
   SHORT_NAME,
   Key,
   LEAD_CO_MNE1,
   BRANCH_CO_MNE1,
   MIS_DATE1,
   DESCRIPTION1,
   SHORT_NAME1,
   New_Flag,
   Changed_Flag,
   o_CREATED_BY,
   o_CREATED_TIME,
   o_UPDATED_BY,
   o_UPDATED_TIME
FROM
   results_with_locals