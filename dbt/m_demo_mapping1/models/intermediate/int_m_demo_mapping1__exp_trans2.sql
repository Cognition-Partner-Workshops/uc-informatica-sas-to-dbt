WITH source_data AS
(
   SELECT
      PRODUCT_NO,
      STD_COST,
      COLOR,
      SELL_ED_DT,
      SELL_ST_DT,
      PRODUCT_ID,
      PRODUCT_NM,
      LIST_PRICE
   FROM
      {{ ref('stg_m_demo_mapping1__sq_demo_source5') }}
)
SELECT
   PRODUCT_NO AS PRODUCT_NO,
   STD_COST AS STD_COST,
   COLOR AS COLOR,
   PRODUCT_ID AS PRODUCT_ID,
   PRODUCT_NM AS PRODUCT_NM,
   LIST_PRICE AS LIST_PRICE,
   TRY_TO_DATE(
   --** SSC-FDM-INF0004 - TO_CHAR EXPRESSION DATA TYPE COULD NOT BE DETERMINED AND MIGHT PRESENT DIFFERENT RESULTS. **
   TO_CHAR(CURRENT_TIMESTAMP()), 'DD/MM/YYYY') AS o_SELL_ST_DT,
   TRY_TO_DATE(SELL_ED_DT, 'DD/MM/YYYY') AS o_SELL_ED_DT
FROM
   source_data